# Foreign keys are matched by (table, column, referenced table) and renamed to
# the convention, rather than by their current name, because that name depends
# on WHEN the database was built: Alembic applies `target_metadata`'s naming
# convention to `op.create_table`, so a database migrated after
# app/models/base.py gained `NAMING_CONVENTION` already has
# `fk_audit_logs_workspace_id_workspaces`, while one migrated before it has the
# server-generated `audit_logs_workspace_id_fkey`. Discovery makes this
# migration correct for both, and idempotent.
_NORMALIZE_FK_NAMES = """
DO $do$
DECLARE
    r record;
    v_current text;
BEGIN
    FOR r IN
        SELECT * FROM (VALUES
            ('ai_narratives',     'project_id',         'projects',
             'fk_ai_narratives_project_id_projects'),
            ('api_keys',          'created_by_user_id', 'users',
             'fk_api_keys_created_by_user_id_users'),
            ('api_keys',          'workspace_id',       'workspaces',
             'fk_api_keys_workspace_id_workspaces'),
            ('audit_logs',        'actor_user_id',      'users',
             'fk_audit_logs_actor_user_id_users'),
            ('audit_logs_default','actor_user_id',      'users',
             'fk_audit_logs_actor_user_id_users'),
            ('findings',          'project_id',         'projects',
             'fk_findings_project_id_projects'),
            ('projects',          'workspace_id',       'workspaces',
             'fk_projects_workspace_id_workspaces'),
            ('proofs_of_concept', 'finding_id',         'findings',
             'fk_proofs_of_concept_finding_id_findings'),
            ('reports',           'project_id',         'projects',
             'fk_reports_project_id_projects'),
            ('subscriptions',     'workspace_id',       'workspaces',
             'fk_subscriptions_workspace_id_workspaces'),
            ('workspace_members', 'workspace_id',       'workspaces',
             'fk_workspace_members_workspace_id_workspaces')
        ) AS t(tbl, col, reftbl, want)
    LOOP
        SELECT c.conname
          INTO v_current
          FROM pg_constraint c
          JOIN pg_attribute a
            ON a.attrelid = c.conrelid AND a.attnum = c.conkey[1]
         WHERE c.contype = 'f'
           AND c.conrelid = r.tbl::regclass
           AND c.confrelid = r.reftbl::regclass
           AND a.attname = r.col;

        IF v_current IS NOT NULL AND v_current <> r.want THEN
            EXECUTE format(
                'ALTER TABLE %I RENAME CONSTRAINT %I TO %I', r.tbl, v_current, r.want);
        END IF;
    END LOOP;
END
$do$;
"""

# Drops whatever the FK on (table, column) is currently called, then recreates
# it under the convention name with the given delete rule. `p_ondelete` of ''
# means NO ACTION, i.e. the database refuses the parent DELETE.
_REDEFINE_FK_FUNCTION = """
CREATE OR REPLACE FUNCTION _vf_redefine_fk(
    p_table text, p_column text, p_ref_table text, p_name text, p_ondelete text
) RETURNS void
LANGUAGE plpgsql
AS $fn$
DECLARE
    v_current text;
BEGIN
    SELECT c.conname
      INTO v_current
      FROM pg_constraint c
      JOIN pg_attribute a
        ON a.attrelid = c.conrelid AND a.attnum = c.conkey[1]
     WHERE c.contype = 'f'
       AND c.conrelid = p_table::regclass
       AND c.confrelid = p_ref_table::regclass
       AND a.attname = p_column;

    IF v_current IS NOT NULL THEN
        EXECUTE format('ALTER TABLE %I DROP CONSTRAINT %I', p_table, v_current);
    END IF;

    IF p_name IS NOT NULL THEN
        EXECUTE format(
            'ALTER TABLE %I ADD CONSTRAINT %I FOREIGN KEY (%I) REFERENCES %I (id) %s',
            p_table, p_name, p_column, p_ref_table,
            CASE WHEN p_ondelete = '' THEN '' ELSE 'ON DELETE ' || p_ondelete END
        );
    END IF;
END;
$fn$;
"""

# `CREATE TABLE ... PARTITION OF` re-validates the DEFAULT partition and
# aborts if it holds any row belonging to the new range, so a late-running
# provisioning job can otherwise never create a partition. This function
# relocates those rows first, which makes partition creation idempotent and
# safe to call at any time. It is SECURITY INVOKER on purpose: the app role
# has no DELETE on audit_logs (SDD §2.4.4 anti-tampering), so only the schema
# owner that runs the scheduled job can execute the relocation path. Normal
# operation keeps the default partition empty by provisioning ahead of time,
# in which case the relocation is a no-op.
_CREATE_PARTITION_FUNCTION = """
CREATE OR REPLACE FUNCTION create_audit_log_partition(p_month date)
RETURNS text
LANGUAGE plpgsql
AS $fn$
DECLARE
    v_start date := date_trunc('month', p_month)::date;
    v_end   date := (date_trunc('month', p_month) + interval '1 month')::date;
    v_name  text := format('audit_logs_y%sm%s', to_char(v_start, 'YYYY'), to_char(v_start, 'MM'));
BEGIN
    IF to_regclass(v_name) IS NOT NULL THEN
        RETURN v_name;
    END IF;

    CREATE TEMP TABLE _audit_logs_relocate AS
        SELECT * FROM audit_logs_default
         WHERE created_at >= v_start AND created_at < v_end;

    DELETE FROM audit_logs_default
     WHERE created_at >= v_start AND created_at < v_end;

    EXECUTE format(
        'CREATE TABLE %I PARTITION OF audit_logs FOR VALUES FROM (%L) TO (%L)',
        v_name, v_start, v_end
    );

    INSERT INTO audit_logs SELECT * FROM _audit_logs_relocate;
    DROP TABLE _audit_logs_relocate;

    RETURN v_name;
END;
$fn$;
"""

# Covers every month that already has data (so nothing is stranded in the
# default partition) through next month (so the scheduled job inherits a
# healthy, ahead-of-time state rather than the trap described above).
_PROVISION_PARTITIONS = """
DO $do$
DECLARE
    v_month date;
BEGIN
    FOR v_month IN
        SELECT generate_series(
            date_trunc('month', COALESCE((SELECT min(created_at) FROM audit_logs), now())),
            date_trunc('month', now()) + interval '1 month',
            interval '1 month'
        )::date
    LOOP
        PERFORM create_audit_log_partition(v_month);
    END LOOP;
END
$do$;
"""

_ASSERT_NO_ORPHANED_AUDIT_ROWS = """
DO $do$
DECLARE
    v_orphans bigint;
BEGIN
    SELECT count(*)
      INTO v_orphans
      FROM audit_logs a
     WHERE NOT EXISTS (SELECT 1 FROM workspaces w WHERE w.id = a.workspace_id);

    IF v_orphans > 0 THEN
        RAISE EXCEPTION
            'Cannot restore the audit_logs -> workspaces foreign key: % audit row(s) reference a workspace that has been purged. Those rows are retained on purpose (SRS UC-04 E2 step 2 / UC-19 E1); archive and remove them explicitly if this downgrade is really intended.',
            v_orphans;
    END IF;
END
$do$;
"""

_ASSERT_NO_CASE_DUPLICATE_EMAILS = """
DO $do$
DECLARE
    v_dupes text;
BEGIN
    SELECT string_agg(d.e, ', ')
      INTO v_dupes
      FROM (
            SELECT lower(email) AS e
              FROM users
             GROUP BY lower(email)
            HAVING count(*) > 1
           ) d;

    IF v_dupes IS NOT NULL THEN
        RAISE EXCEPTION
            'Cannot enforce case-insensitive email uniqueness: % already exists under more than one casing. Merge or rename those accounts first.',
            v_dupes;
    END IF;
END
$do$;
"""



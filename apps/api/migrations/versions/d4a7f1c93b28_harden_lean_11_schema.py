def downgrade() -> None:
    """Downgrade schema."""
    # --- 2. monthly partitions -------------------------------------------
    # Rows are moved back into the default partition before each monthly
    # partition is dropped, so downgrading never loses audit data. The DETACH
    # has to come first: while a monthly partition is still attached, the
    # default partition's implicit constraint excludes that month's range and
    # a direct INSERT into it would be rejected.
    op.execute(
        """
        DO $do$
        DECLARE
            v_part text;
        BEGIN
            FOR v_part IN
                SELECT c.relname
                  FROM pg_class c
                  JOIN pg_inherits i ON i.inhrelid = c.oid
                 WHERE i.inhparent = 'audit_logs'::regclass
                   AND c.relname <> 'audit_logs_default'
            LOOP
                EXECUTE format(
                    'ALTER TABLE audit_logs DETACH PARTITION %I', v_part);
                EXECUTE format(
                    'INSERT INTO audit_logs_default SELECT * FROM %I', v_part);
                EXECUTE format('DROP TABLE %I', v_part);
            END LOOP;
        END
        $do$;
        """
    )
    op.execute("DROP FUNCTION IF EXISTS create_audit_log_partition(date)")

    # --- 5 + 1. restore the previous delete rules ------------------------
    # Foreign key *names* are deliberately not reverted: `Base.metadata` now
    # carries the naming convention at every revision, so the convention names
    # are what the models declare and what Alembic expects to reflect. Only
    # the semantics (delete rules, and the audit_logs FK itself) are reverted.
    op.execute(_REDEFINE_FK_FUNCTION)
    op.execute(
        "SELECT _vf_redefine_fk('projects', 'lead_pentester_id', 'users', "
        "'fk_projects_lead_pentester_id_users', '')"
    )
    op.execute(
        "SELECT _vf_redefine_fk('workspace_members', 'user_id', 'users', "
        "'fk_workspace_members_user_id_users', 'CASCADE')"
    )
    # Restoring the workspace FK means re-validating every audit row, and PG
    # does not allow NOT VALID foreign keys on partitioned tables ("This
    # feature is not yet supported"), so there is no way to re-attach it while
    # keeping rows whose workspace has been purged. Rather than silently
    # deleting compliance evidence to make a rollback succeed, refuse with an
    # actionable message — the pre-fix schema simply cannot represent that
    # data. In dev/CI, where no workspace has been purged, this is a no-op.
    op.execute(_ASSERT_NO_ORPHANED_AUDIT_ROWS)
    op.execute(
        "SELECT _vf_redefine_fk('audit_logs', 'workspace_id', 'workspaces', "
        "'fk_audit_logs_workspace_id_workspaces', 'CASCADE')"
    )
    op.execute("DROP FUNCTION _vf_redefine_fk(text, text, text, text, text)")

    # --- 6. midtrans_order_id back to a non-unique index -----------------
    op.drop_index("ix_subscriptions_midtrans_order_id", table_name="subscriptions")
    op.create_index(
        "ix_subscriptions_midtrans_order_id",
        "subscriptions",
        ["midtrans_order_id"],
        unique=False,
    )

    # --- 3. drop case-insensitive email uniqueness -----------------------
    op.drop_index("uq_users_email_lower", table_name="users")

    # --- 4. drop findings.created_at -------------------------------------
    op.drop_column("findings", "created_at")
